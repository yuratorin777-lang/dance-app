import { NextRequest, NextResponse } from 'next/server';
import knowledgeBase from '@/data/knowledgebase.json';

export const dynamic = 'force-dynamic';

export async function POST(req: NextRequest) {
  try {
    const { messages } = await req.json();

    const apiKey = process.env.GROQ_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        { reply: "[Ошибка]: GROQ_API_KEY не найден в .env.local" },
        { status: 200 }
      );
    }

    const systemPrompt = `
Ты — Катерина, заботливый администратор и консультант школы детских танцев "Baby Dance".
Твоя цель — мягко расположить родителя, отвечать на вопросы, проявлять искренний интерес к ребёнку и подводить к записи на Первое занятие.

БАЗА ЗНАНИЙ ШКОЛЫ:
${JSON.stringify(knowledgeBase, null, 2)}

ПРАВИЛА ПРОДАЖ И ОБЩЕНИЯ:
1. **Тон общения:** Тёплый, эмпатичный, профессиональный, но без официальщины и штампов. Общайся так, будто пишешь маме в WhatsApp.
2. **СТРОГОЕ ОГРАНИЧЕНИЕ ПО ОБЪЕМУ:** Отвечай КРАТКО (2-4 коротких предложения). Мамы читают с телефона, длинные "простыни" текста читать никто не будет!
3. **Структура ответа:**
   - Короткий прямой ответ на вопрос родителя (без воды).
   - Элемент заботы/поддержки.
   - Встречный вовлекающий вопрос (чтобы диалог продолжался естественным образом).
4. **О ПЕРВОМ ЗАНЯТИИ:** 
   - Мы НЕ используем слова "пробное занятие", "проба", "попробовать". Результат в танцах даёт только регулярность.
   - Мы приглашаем на "Первое занятие" или предлагаем "записаться в группу / записать ребёнка на первое занятие".
5. **ИМЯ РЕБЁНКА:** Если родитель не назвал имя и возраст ребёнка — при первой возможности мягко спроси, как зовут малыша и сколько ему лет. Если имя названо — используй его в диалоге!
6. **Запреты:**
   - НЕ штампуй фразы "Заполни форму на этой странице" в каждом сообщении!
   - НЕ используй заезженные фраземы ("танцевальное путешествие", "реализовать проект").
   - НЕ вываливай всю базу данных сразу.

ПРИМЕРЫ ХОРОШИХ ОТВЕТОВ:

Вопрос: "В чем приводить ребенка?"
Ответ: "На первое занятие отлично подойдет любая удобная спортивная форма или легинсы с футболкой, чистая сменная обувь и бутылочка воды. Главное — чтобы малышу было комфортно двигаться! Подскажите, как зовут вашего ребёночка и сколько ему лет?"

Вопрос: "Сколько стоит индивидуальное занятие?"
Ответ: "Индивидуальные уроки у нас есть двух форматов: 30 минут (800 руб.) — для мягкой адаптации, и 45 минут (1 200 руб.) — для углубленной работы и номеров. Скажите, вы хотите позаниматься индивидуально, чтобы ребёнок освоился перед групповыми занятиями?"

Вопрос: "Сколько стоит абонемент?"
Ответ: "Абонемент на 8 занятий стоит 3 200 рублей. Занятия проходят 2 раза в неделю в мини-группах до 9 человек, чтобы преподаватель уделял внимание каждому. Подсказать вам расписание для вашей возрастной группы?"
`;

    const formattedMessages = [
      { role: 'system', content: systemPrompt },
      ...messages.map((m: { role: string; content: string }) => ({
        role: m.role === 'user' ? 'user' : 'assistant',
        content: m.content
      }))
    ];

    const response = await fetch("https://api.groq.com/openai/v1/chat/completions", {
      method: "POST",
      headers: {
        "Authorization": `Bearer ${apiKey}`,
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        model: "openai/gpt-oss-120b",
        messages: formattedMessages,
        temperature: 0.4,
        max_tokens: 300
      })
    });

    if (!response.ok) {
      const errData = await response.json();
      return NextResponse.json(
        { reply: `[Ошибка Groq API ${response.status}]: ${errData?.error?.message || response.statusText}` },
        { status: 200 }
      );
    }

    const data = await response.json();
    const reply = data.choices?.[0]?.message?.content || "Извините, не удалось сформировать ответ.";

    return NextResponse.json({ reply });

  } catch (error: any) {
    return NextResponse.json(
      { reply: `[Ошибка сервера]: ${error.message}` },
      { status: 200 }
    );
  }
}